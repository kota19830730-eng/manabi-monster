  function progress(xp) {
    const level = levelOf(xp);
    const base = xpForLevel(level);
    const nextXp = xpForLevel(level + 1);
    return { level: level, into: xp - base, need: nextXp - base, ratio: (xp - base) / (nextXp - base) };
  }

