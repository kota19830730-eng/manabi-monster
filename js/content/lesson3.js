  // 問題文の 中の 数字（小数も）を 左から
  function nums(q) {
    const t = String(q.prompt || '').replace(/<[^>]+>/g, ' ');
    return (t.match(/\d+(?:\.\d+)?/g) || []).map(Number);
  }
  function txt(q) { return String(q.prompt || '').replace(/<[^>]+>/g, ' '); }
  function step(when, fn) { return { when: when, make: fn }; }
  function pick3(ask, ok, ng1, ng2, why) { return { ask: ask, choices: [ok, ng1, ng2], why: why }; }
  const ASK = 'まず なにを する？';
  function near(v, x) { return Math.abs(Number(v) - Number(x)) < 1e-9; }
  function ex(html) { return '<div class="dojo__ex">' + html + '</div>'; }
  function line(s) { return '<p>' + s + '</p>'; }
  // 解説の 図（v14.18）：問題の 図（sansu3.js の figs3）を 大きく 見せる
  function fig(svg) { return '<div class="dojo__fig">' + svg + '</div>'; }
