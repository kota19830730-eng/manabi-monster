/* ---------------------------------------------------------
   しゅぎょうば の 指導の 中身（v13.0）：小3 算数 18ステージ

   相棒（連れて 歩いて いる なかま）が となりで 声を かけながら 教える ための 文。
   問題そのものは いままでの 生成器（sansu3.js の make）を そのまま 使う。
   ここに あるのは
     intro   … さいしょの ひとこと
     explain … せつめい（2〜3画面。say＝相棒の ことば・ex＝例の カードの HTML）
     steps   … 「まず なにを する？」の 3たく（unit に 当てる 正規表現 → 問題の 数字入りで 作る）
               choices は 正しい ものを 先頭に（画面で まぜる）
     miss    … まちがい方に 合わせた 声かけ（上から 見て さいしょに 文字を かえした もの）
   文は 小3までの かん字＋ひらがな・文節ごとに スペース（smoke が 検査）。
   「にがて」と 書かない・答えを ばかに しない・つぎに つながる ことばで おわる。

   ルール（合格・ごほうび・一覧）は js/core/dojo.js、画面は js/ui/dojo.js。
   --------------------------------------------------------- */
window.MQ = window.MQ || {};

MQ.lessons = MQ.lessons || (function () {
  const table = {};
  function add(stageId, lesson) { lesson.id = stageId; table[stageId] = lesson; return lesson; }
  function get(stageId) { return table[stageId] || null; }
  function has(stageId) { return !!table[stageId]; }
  function ids() { return Object.keys(table); }
  return { add: add, get: get, has: has, ids: ids, table: table };
})();

