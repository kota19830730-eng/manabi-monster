  function clocks(a, b, mid) {
    const C = MQ.sansu1.clockHtml;
    return '<div class="dojo__fig dojo__fig--row"><span class="clockbox">' + C(a[0], a[1]) + '</span><span class="dojo__fig__mid">' + mid + '</span><span class="clockbox">' + C(b[0], b[1]) + '</span></div>';
  }
  function fracs(list) {
    return '<div class="dojo__fig dojo__fig--row">' + list.map(function (e) { return typeof e === 'string' ? '<span class="dojo__fig__mid">' + e + '</span>' : MQ.sansu2.fracSvg(e[0], e[1]); }).join('') + '</div>';
  }

