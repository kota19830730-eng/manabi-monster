  // れい文の ＿ に inner（HTML）を 入れた もの。れい文が なければ null
  function fill(grade, k, inner) {
    const s = DATA[grade] && DATA[grade][k];
    if (!s) return null;
    const i = s.indexOf('＿');
    return s.slice(0, i) + inner + s.slice(i + 1);
  }

  // 書く 問題・読む 問題の 文（kanjiq.js と 小3の 書く 問題が つかう）
  function kakiText(grade, k, r) {
    const c = fill(grade, k, '<b class="kr">' + r + '</b>');
    return c ? { text: '「' + c + '」の「' + r + '」を かん字で かくと？', ctx: c } : null;
  }
  function yomiText(grade, k) {
    const c = fill(grade, k, '<b class="kr">' + k + '</b>');
    return c ? '「' + c + '」の「' + k + '」の よみかたは？' : null;
  }

  /* 小3の 書く 問題は kokugo3.js に 手で 書いて ある（「およぐ」を かん字で書くと？）。
     kokugo3.js は この ファイルより 先に 読む ので、ここで れい文つきに 書きかえる */
  if (MQ.kokugo3 && MQ.kokugo3.questions) {
    MQ.kokugo3.questions.forEach(function (q) {
      if (q.stage !== 2) return;
      const m = q.text.match(/「([^」]+)」(?:（[^）]*）)?を かん字で書くと？$/);   // （気温）の ような 前の ヒントは れい文に おきかえる
      if (!m) return;
      const c = fill(3, q.choices[0], '<b class="kr">' + m[1] + '</b>');
      if (!c) return;
      q.text = '「' + c + '」の「' + m[1] + '」を かん字で書くと？';
      q.yomi = m[1]; q.ctx = c;
    });
  }

  return { data: DATA, fill: fill, kakiText: kakiText, yomiText: yomiText };
