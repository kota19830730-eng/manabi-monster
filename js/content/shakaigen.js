  function histQ() {
    const out = [];
    HIST.forEach(function (r, i) {
      const spec = { stage: r[4], unit: r[5] };
      const ev = r[0], era = r[1], who = r[2], yr = r[3];
      const sameStage = HIST.filter(function (x) { return x[4] === r[4]; });
      // 何時代？（となりの 時代を まちがいに）
      const ei = ERAS.indexOf(era);
      const near = [ei - 1, ei + 1, ei - 2, ei + 2, ei + 3, ei - 3].filter(function (k) { return k >= 0 && k < ERAS.length; }).map(function (k) { return ERAS[k]; });
      out.push(H.mk(spec, 2, '「' + ev + '」のは 何時代？', [era + '時代'].concat(near.slice(0, 3).map(function (e) { return e + '時代'; })), ev + 'のは ' + era + '時代。', '年表の ならびを 思い出そう。'));
      // 人物
      if (who && ev.indexOf(who) < 0 && ev.indexOf(who.slice(0, 2)) < 0) {
        const ppl = [];
        sameStage.forEach(function (x) { if (x[2] && x[2] !== who && ppl.indexOf(x[2]) === -1) ppl.push(x[2]); });
        const pd = [ppl[(i * 3) % ppl.length], ppl[(i * 3 + 4) % ppl.length], ppl[(i * 3 + 7) % ppl.length]];
        out.push(H.mk(spec, 2, '「' + ev + '」に 関係の 深い 人物は？', [who].concat(pd), ev + ' ＝ ' + who + '。', era + '時代の 人。'));
        // 人物 → できごと（同じ 人物の ほかの できごとは まちがいに 入れない）
        const evs = sameStage.filter(function (x) { return x[2] !== who; });
        const ed = [evs[(i * 5) % evs.length][0], evs[(i * 5 + 3) % evs.length][0], evs[(i * 5 + 8) % evs.length][0]];
        out.push(H.mk(spec, 3, '「' + who + '」が した ことは？', [ev].concat(ed), who + '：' + ev + '。', era + '時代の 人。'));
      }
      // 何年？
      if (yr) {
        const yrs = [];
        sameStage.forEach(function (x) { if (x[3] && x[3] !== yr && yrs.indexOf(x[3]) === -1) yrs.push(x[3]); });
        const yd = [yrs[(i * 3) % yrs.length], yrs[(i * 3 + 2) % yrs.length], yrs[(i * 3 + 5) % yrs.length]];
        out.push(H.mk(spec, 3, '「' + ev + '」のは 何年？', [yr + '年'].concat(yd.map(function (y) { return y + '年'; })), yr + '年：' + ev + '。', era + '時代。'));
      }
      // 同じ 時代の できごと
      const same = sameStage.filter(function (x) { return x[1] === era && x[0] !== ev; });
      const diff = sameStage.filter(function (x) { return x[1] !== era; });
      if (same.length && diff.length >= 3) {
        out.push(H.mk(spec, 3, '「' + ev + '」と 同じ 時代の できごとは？', [same[i % same.length][0], diff[(i * 7) % diff.length][0], diff[(i * 7 + 5) % diff.length][0], diff[(i * 7 + 11) % diff.length][0]], 'どちらも ' + era + '時代。', era + '時代の できごとを さがそう。'));
      }
    });
    return out;
  }

