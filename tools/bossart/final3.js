const K = 1.5, J = G.join;
const rr = function (v) { return Math.round(v * K); };
const P = function (pts, k, f) { return G.poly(pts.map(function (p) { return [p[0] * K, p[1] * K]; }), k, f); };
const L = function (a, b, k, t, f) { return G.line([a[0] * K, a[1] * K], [b[0] * K, b[1] * K], k, (t || 2) * K, f); };
const Q = function (x, y, w, h, k, f) { return G.rect(rr(x), rr(y), rr(x + w) - rr(x), rr(y + h) - rr(y), k, f); };
